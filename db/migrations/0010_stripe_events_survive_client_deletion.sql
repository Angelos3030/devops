-- Το ιστορικό γεγονότων Stripe ΕΠΙΒΙΩΝΕΙ της διαγραφής του πελάτη.
--
-- ΤΟ ΣΦΑΛΜΑ. Ένα ΕΓΚΥΡΑ ΥΠΟΓΕΓΡΑΜΜΕΝΟ event με `client_id` που είναι σωστό
-- uuid αλλά δεν υπάρχει πια στο `clients` έριχνε τον webhook:
--
--     insert or update on table "stripe_events" violates foreign key
--     constraint "stripe_events_client_id_fkey"      → HTTP 500
--
-- Το Stripe ξαναπροσπαθεί σε 5xx με backoff έως τρεις ημέρες και, μετά από
-- επαναλαμβανόμενες αποτυχίες, ΑΠΕΝΕΡΓΟΠΟΙΕΙ το endpoint. Τότε σταματά η
-- επεξεργασία γεγονότων για ΟΛΟΥΣ τους πελάτες — όχι μόνο για τον έναν που
-- διαγράφηκε. Ένα event που αφορά διαγραμμένο πελάτη γινόταν έτσι δηλητήριο
-- για ολόκληρο το billing.
--
-- Η ΑΙΤΙΑ ΕΙΝΑΙ ΑΡΧΙΤΕΚΤΟΝΙΚΗ, ΟΧΙ ΛΟΓΙΚΗ. Το `process_stripe_billing_event`
-- ΗΔΗ χειρίζεται σωστά τον άγνωστο πελάτη:
--
--     IF v_client_id IS NULL OR NOT EXISTS (SELECT 1 FROM clients …) THEN
--       processing_status = 'ignored_unknown', result_code = 'unknown_client'
--
-- Απλώς δεν έφτανε ποτέ εκεί: το INSERT στο ledger γίνεται ΠΡΙΝ από αυτόν τον
-- έλεγχο και έσκαγε στο FK. Δεν χρειάζεται αλλαγή λογικής — χρειάζεται να
-- πάψει το ledger να απαιτεί ζωντανό πελάτη.
--
-- ΓΙΑΤΙ ΦΕΥΓΕΙ ΤΟ FK ΚΑΙ ΔΕΝ ΓΙΝΕΤΑΙ DEFERRABLE Ή SENTINEL:
--
-- Ένα γεγονός Stripe είναι **ιστορικό**: συνέβη, και συνέβη για συγκεκριμένο
-- αναγνωριστικό. Ο τοπικός πελάτης μπορεί να διαγραφεί νόμιμα (GDPR, admin)
-- ενώ το Stripe συνεχίζει να στέλνει events για τη συνδρομή του. Ένα ledger
-- ελέγχου που απαιτεί να ζει ακόμα η οντότητα δεν είναι ledger ελέγχου.
--
-- Το `ON DELETE SET NULL` που υπήρχε ΕΣΒΗΝΕ την πληροφορία: μετά τη διαγραφή
-- κανείς δεν μπορούσε να πει σε ποιον αφορούσε το γεγονός. Κρατώντας το
-- αναγνωριστικό ως καθαρό μεταδεδομένο, το ιστορικό παραμένει χρήσιμο για
-- έλεγχο, idempotency, replay και διάγνωση — που είναι ο λόγος ύπαρξής του.
--
-- Sentinel πελάτης απορρίφθηκε: θα εφεύρισκε οντότητα που δεν υπήρξε ποτέ και
-- θα μόλυνε κάθε ερώτημα που μετρά πελάτες.
--
-- ΤΙ ΔΕΝ ΑΛΛΑΖΕΙ: η στήλη, το index, ο έλεγχος `processing_status`, το πρωτεύον
-- κλειδί στο `stripe_event_id` (η idempotency), και ολόκληρη η λογική του RPC.
-- Καμία εξουσιοδότηση δεν χαλαρώνει και καμία υπογραφή δεν παρακάμπτεται: ο
-- έλεγχος υπογραφής γίνεται στο FastAPI, πολύ πριν φτάσει εδώ.
--
-- ΣΗΜΕΙΩΣΗ ΔΙΑΤΗΡΗΣΗΣ: μετά από αυτό, η διαγραφή πελάτη ΔΕΝ σβήνει πια το
-- αναγνωριστικό του από το ιστορικό γεγονότων. Είναι ψευδώνυμο αναγνωριστικό
-- (uuid), όχι προσωπικό δεδομένο — αλλά η πολιτική διατήρησης του ledger είναι
-- απόφαση προϊόντος/νομικής, όχι αυτού του migration. Αναφέρεται, δεν ορίζεται
-- εδώ.

ALTER TABLE public.stripe_events
  DROP CONSTRAINT IF EXISTS stripe_events_client_id_fkey;

COMMENT ON COLUMN public.stripe_events.client_id IS
  'Ο πελάτης που αφορούσε το γεγονός, ως ΜΕΤΑΔΕΔΟΜΕΝΟ ΕΛΕΓΧΟΥ. Χωρίς foreign '
  'key επίτηδες: ένα γεγονός Stripe επιβιώνει της διαγραφής του τοπικού '
  'πελάτη. Η ύπαρξη του πελάτη ελέγχεται ρητά μέσα στο '
  'process_stripe_billing_event, που κατατάσσει το γεγονός ως '
  'ignored_unknown / unknown_client.';
