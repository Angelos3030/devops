/** Οι δυνατότητες ενός theme. Άγνωστο id -> τίποτα επιτρεπτό. */
export function getThemeCapabilities(themeId) {
  const c = THEME_CAPABILITIES[themeId]
  if (!c) return { cls: 'C', mode: 'light', palettes: [], typography: [], logo: true }
  return c
}

/** Επιτρέπεται αυτή η συγκεκριμένη αλλαγή; Ίδια απάντηση με το backend. */
export function isAllowed(themeId, op, value) {
  const c = getThemeCapabilities(themeId)
  if (op === 'set_palette') return value === 'original' || c.palettes.includes(value)
  if (op === 'set_font_pair') return c.typography.includes(value)
  if (op === 'set_logo') return c.logo
  return false
}
